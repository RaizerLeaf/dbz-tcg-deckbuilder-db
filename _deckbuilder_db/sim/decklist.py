"""Generates DECK_LIST.md: every deck file in decks/ and sim/decks/, best roster win rate first.

    python -m sim decklist          regenerate by hand (also done automatically by `roster add` and `roster rebuild`)

Order: the roster decks by rank (round-robin win rate, best first), then decks that are off the roster (retired / superseded) by the win rate they had when they left,
then decks that never ranked (comparison builds, not modelled) by file name. The hand-written status text for each deck lives in sim/deck_notes.json
(`{"decks/x.txt": {"mp": "...", "status": "..."}}`); edit that file, never DECK_LIST.md. Rank and win-rate columns come from sim/roster.json.
"""
import json
from pathlib import Path

SIM = Path(__file__).resolve().parent
DB = SIM.parent
DECK_LIST_FILE = DB / 'DECK_LIST.md'
NOTES_FILE = SIM / 'deck_notes.json'
DECK_DIRS = ('decks', 'sim/decks')

HEADER = """# Deck list (best performing first)

**Generated by `python -m sim decklist` from `sim/roster.json` and `sim/deck_notes.json`. Do not edit by hand** (it is rewritten every time `python -m sim roster add|rebuild` runs, so the order
follows the win rates as new decks are tested). To change a deck's status text, edit `sim/deck_notes.json`.
Win % = the deck's round-robin win rate against the other roster decks in the simulator (a toy model, see `sim/README.md`), measured at the moment of the last roster update; numbers inside the
Status text were written at the time of the deck and may be older. `decks/` holds decks built in cloud sessions or exported by the owner, `sim/decks/` holds older simulation decks.
Only codes the owner imported are confirmed to load in the app (the Status says so).
"""


def _notes():
    return json.loads(NOTES_FILE.read_text(encoding='utf-8')) if NOTES_FILE.exists() else {}


def _cell(t):
    return (t or '-').replace('|', '/').replace('\n', ' ')


def build(roster):
    notes = _notes()
    files = sorted(p.relative_to(DB).as_posix() for d in DECK_DIRS for p in (DB / d).glob('*.txt'))
    on = {d['file']: (i, d) for i, d in enumerate(roster.get('decks', []), 1)}
    off = {}
    for key in ('retired', 'superseded'):
        for d in roster.get(key, []):
            off[d['file']] = (key, d)
    out = [HEADER]

    def mp_of(f, d=None):
        if d:
            return f"{d['mp']} / {d['mastery']}"
        try:
            from .loader import load
            sp = load(str(DB / f))
            return f'{sp.mp_name} / {sp.mastery_name}'
        except Exception:
            return '-'

    out.append(f"## On the roster (ranked, {len(on)} of {roster.get('max', 25)})\n")
    out.append('| Rank | Win % | Avg turn of wins | Deck file | MP / Mastery | Status |')
    out.append('|---|---|---|---|---|---|')
    for f, (i, d) in sorted(on.items(), key=lambda kv: kv[1][0]):
        out.append(f"| {i} | {d['win_pct']}% | {d.get('avg_turn_of_wins') or '-'} | `{f}` | {_cell(mp_of(f, d))} | {_cell(notes.get(f, {}).get('status'))} |")
    out.append('')

    left = [f for f in files if f in off and f not in on]
    out.append('## Off the roster: retired or replaced by a better version of the same deck (by the win rate they had when they left)\n')
    out.append('| Win % then | Why | Deck file | MP / Mastery | Status |')
    out.append('|---|---|---|---|---|')
    for f in sorted(left, key=lambda f: -off[f][1]['win_pct']):
        kind, d = off[f]
        why = 'retired (below the top 25)' if kind == 'retired' else f"superseded by `{d.get('superseded_by')}`"
        out.append(f"| {d['win_pct']}% | {why} | `{f}` | {_cell(mp_of(f, d))} | {_cell(notes.get(f, {}).get('status'))} |")
    out.append('')

    never = [f for f in files if f not in on and f not in off]
    out.append('## Never ranked (comparison builds, drafts, or decks the simulator cannot rank)\n')
    out.append('| Deck file | MP / Mastery | Status |')
    out.append('|---|---|---|')
    for f in never:
        out.append(f"| `{f}` | {_cell(mp_of(f))} | {_cell(notes.get(f, {}).get('status'))} |")
    out.append('')
    return '\n'.join(out)


def write(roster, path=None):
    (path or DECK_LIST_FILE).write_text(build(roster), encoding='utf-8')
